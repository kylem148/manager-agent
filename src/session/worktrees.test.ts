/**
 * Tests for the worktree lifecycle harness, run against a real throwaway git
 * repo — the local half IS git plumbing, so faking git would prove nothing —
 * with the remote half (fetch, and the `origin/dev` the flow is anchored on)
 * served by the fake forge. No network, no gh binary.
 *
 * Each test builds a fresh repo with a main branch, a commit, a .gitignore
 * matching the real repo's posture (node_modules/ and dist/ ignored), build
 * artifacts in the primary tree that provision must NOT touch, and an
 * `origin/dev` on the fake remote. The managed worktree base is a sibling dir
 * inside the same tmp root, mirroring the default layout.
 *
 * The base fixture is deliberately not an npm package, so provision has no
 * lockfile to install from and every test that only cares about git plumbing
 * stays fast. `makeRepo({ nodePackage: true })` opts into a real one for the
 * tests that need a real install to run, and `buildsOnPrepare` gives that
 * package a `prepare` script the way this repo has one, so the install produces
 * a real build directory too.
 *
 * The tmp root is realpath'd up front: macOS spells os.tmpdir() as /var/...
 * while git reports the /private/var/... realpath, and the module's path
 * comparisons must not be fooled by that (nor the tests').
 */

/** A real npm package whose only dependency is a directory inside the repo, so
 *  a real `npm ci` installs something without ever reaching the network. */
const PKG = { name: "fixture", version: "1.0.0", dependencies: { "fixture-dep": "file:dep" } };
const DEP_PKG = { name: "fixture-dep", version: "1.0.0" };

/** A `prepare` script of the same shape as this repo's own (`tsc && chmod +x
 *  dist/index.js`): an install compiles the package, so a plain `npm ci` writes
 *  a real dist/ as a side effect. It records the directory it ran in, which is
 *  what lets a test prove the dist belongs to the tree it sits in. */
const PREPARE_BUILD =
  "node -e \"const fs=require('fs');fs.mkdirSync('dist',{recursive:true});" +
  "fs.writeFileSync('dist/built.txt',process.cwd())\"";

function run(cwd: string, args: string[]): string {
  const res = spawnSync("git", args, { cwd, encoding: "utf8" });
  if (res.status !== 0) {
    throw new Error(`git ${args.join(" ")} failed (${res.status}): ${res.stderr}`);
  }
  return res.stdout.trim();
}

async function makeRepo(extra: { nodePackage?: boolean; buildsOnPrepare?: boolean } = {}): Promise<{
  root: string;
  repo: string;
  base: string;
  forge: FakeForge;
  /** WorktreeOptions for this repo, wired to the fake forge. */
  opts: { repoPath: string; baseDir: string; run: FakeForge["run"] };
  cleanup: () => Promise<void>;
}> {
  const root = await fsp.realpath(await fsp.mkdtemp(path.join(os.tmpdir(), "co-worktree-")));
  const repo = path.join(root, "repo");
  const base = path.join(root, "worktrees");
  await fsp.mkdir(repo);
  run(repo, ["init", "-q", "-b", "main"]);
  run(repo, ["config", "user.email", "test@test"]);
  run(repo, ["config", "user.name", "test"]);
  run(repo, ["config", "commit.gpgsign", "false"]);
  await fsp.writeFile(path.join(repo, "file.txt"), "hello\n", "utf8");
  await fsp.writeFile(path.join(repo, ".gitignore"), "node_modules/\ndist/\n", "utf8");
  if (extra.nodePackage) {
    // A real, installable npm package. `npm ci` does everything it really does
    // here, including the destructive "empty node_modules first" step that is
    // the whole point, but the one dependency is a local directory so it needs
    // no network and finishes in milliseconds. The lockfile is generated by the
    // local npm rather than hand-written, so it stays right across npm versions.
    const pkg = extra.buildsOnPrepare ? { ...PKG, scripts: { prepare: PREPARE_BUILD } } : PKG;
    await fsp.writeFile(path.join(repo, "package.json"), `${JSON.stringify(pkg, null, 2)}\n`, "utf8");
    await fsp.mkdir(path.join(repo, "dep"));
    await fsp.writeFile(path.join(repo, "dep", "package.json"), `${JSON.stringify(DEP_PKG, null, 2)}\n`, "utf8");
    // --ignore-scripts: writing the lockfile runs `prepare` too, and a dist/ built
    // here would collide with the primary tree's own further down. Nothing about
    // what a later `npm ci` does is affected by it.
    const lock = spawnSync("npm", ["install", "--package-lock-only", "--ignore-scripts", "--silent"], {
      cwd: repo,
      encoding: "utf8",
    });
    if (lock.status !== 0) throw new Error(`fixture lockfile generation failed: ${lock.stderr}`);
  }
  run(repo, ["add", "."]);
  run(repo, ["commit", "-q", "-m", "init"]);
  // Build artifacts in the PRIMARY tree. Provision must never link to these and
  // nothing done in a worktree may reach them; several tests assert exactly that.
  await fsp.mkdir(path.join(repo, "node_modules"));
  await fsp.writeFile(path.join(repo, "node_modules", "marker.txt"), "deps\n", "utf8");
  await fsp.mkdir(path.join(repo, "dist"));
  await fsp.writeFile(path.join(repo, "dist", "marker.txt"), "build\n", "utf8");
  // The integration branch lives on the remote; co only ever reads origin/dev.
  const forge = makeFakeForge(repo, { dev: run(repo, ["rev-parse", "main"]) });
  return {
    root,
    repo,
    base,
    forge,
    opts: { repoPath: repo, baseDir: base, run: forge.run },
    cleanup: () => fsp.rm(root, { recursive: true, force: true }),
  };
}

function sha(repo: string, ref: string): string {
  return run(repo, ["rev-parse", ref]);
}

function branchExists(repo: string, branch: string): boolean {
  const res = spawnSync("git", ["show-ref", "--verify", "--quiet", `refs/heads/${branch}`], {
    cwd: repo,
    encoding: "utf8",
  });
  return res.status === 0;
}

/** Add a commit to a branch that has no checkout, with plumbing only — the
 *  "unmerged work whose worktree is gone" state, built without a worktree. */
function commitOnBranch(repo: string, branch: string): void {
  const parent = run(repo, ["rev-parse", branch]);
  const tree = run(repo, ["rev-parse", `${branch}^{tree}`]);
  const sha = run(repo, ["commit-tree", "-p", parent, "-m", "unmerged work", tree]);
  run(repo, ["update-ref", `refs/heads/${branch}`, sha]);
}

