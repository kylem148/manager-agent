test("provisionWorktree cuts <type>/<slug> from origin/dev and links no build artifacts", async () => {
  const { repo, base, opts, forge, cleanup } = await makeRepo();
  try {
    // Make origin/dev and main genuinely different, so "based off origin/dev"
    // is provable: the remote's dev sits at today's main, then main advances.
    const devSha = forge.branches.get("dev")!;
    await fsp.writeFile(path.join(repo, "file.txt"), "main moved on\n", "utf8");
    run(repo, ["commit", "-qam", "advance main"]);
    const mainSha = sha(repo, "main");
    assert.notEqual(mainSha, devSha);

    const rec = await provisionWorktree(opts, "My Feature");
    assert.equal(rec.branch, "feat/my-feature");
    assert.equal(rec.worktreePath, path.join(base, "my-feature"));
    assert.equal(rec.provisionStatus, "ready");

    // A real checkout on the feature branch, at origin/dev's tip — not main's.
    assert.ok(fs.existsSync(path.join(rec.worktreePath, "file.txt")));
    assert.equal(run(rec.worktreePath, ["rev-parse", "--abbrev-ref", "HEAD"]), rec.branch);
    assert.equal(sha(rec.worktreePath, "HEAD"), devSha);
    // --no-track: the feature branch must not adopt origin/dev as its upstream
    // (git exits 1 for a config key that isn't there, which is the assertion).
    assert.equal(
      spawnSync("git", ["config", "--get", `branch.${rec.branch}.remote`], { cwd: repo }).status,
      1,
      "the feature branch has no upstream of its own",
    );

    // ISOLATION: nothing in the worktree points at the primary's build output.
    // A link here is the defect this module exists to have stopped making.
    for (const name of ["node_modules", "dist"]) {
      const inWorktree = await fsp.lstat(path.join(rec.worktreePath, name)).catch(() => null);
      assert.equal(inWorktree, null, `${name} is not provisioned into the worktree at all`);
      // And the primary's own copy is untouched by any of it.
      assert.equal(
        await fsp.readFile(path.join(repo, name, "marker.txt"), "utf8"),
        name === "dist" ? "build\n" : "deps\n",
      );
    }
    // No lockfile in this fixture, so there is no honest install to run.
    assert.deepEqual(rec.dependencies, { status: "skipped", reason: "no lockfile to install from" });

    assert.equal(sha(repo, "main"), mainSha, "main untouched");
  } finally {
    await cleanup();
  }
});

/**
 * THE REGRESSION. An earlier build symlinked the worktree's node_modules back to
 * the primary tree, and `npm ci` opens by reading node_modules and deleting every
 * entry it finds — through the link, that was the CAPTAIN'S dependencies, gone in
 * one command a crew agent runs as a matter of routine.
 *
 * Deliberately a real `npm ci`, not a fake: the bug lived entirely in what a real
 * package manager does to a real symlink, so anything faked here would pass
 * against the broken code too. The fixture has no dependencies, so it needs no
 * network and the destructive step still runs in full.
 */
test("a crew agent's npm ci in a worktree cannot reach the primary tree's dependencies", async () => {
  const { repo, opts, cleanup } = await makeRepo({ nodePackage: true });
  try {
    const rec = await provisionWorktree(opts, "auth");
    assert.equal(rec.dependencies?.status, "installed", "the repo's own frozen install ran");
    assert.equal(rec.dependencies?.command, "npm ci");

    // What provision left is the worktree's OWN directory, not a link out of it.
    const nm = await fsp.lstat(path.join(rec.worktreePath, "node_modules"));
    assert.ok(nm.isDirectory() && !nm.isSymbolicLink(), "node_modules is the worktree's own dir");

    const res = spawnSync("npm", ["ci"], { cwd: rec.worktreePath, encoding: "utf8" });
    assert.equal(res.status, 0, `npm ci failed: ${res.stderr}`);

    assert.equal(
      await fsp.readFile(path.join(repo, "node_modules", "marker.txt"), "utf8"),
      "deps\n",
      "the primary tree's dependencies survived a crew agent's reinstall",
    );
  } finally {
    await cleanup();
  }
});

/**
 * THE OTHER HALF OF THE SAME REGRESSION. The old build symlinked dist/ back to
 * the primary tree as well, and that link was the quieter of the two faults: a
 * build run in a worktree wrote through it into the primary's dist, which is the
 * dist the captain's installed `co` actually executes, so their tool was
 * silently swapped for unreviewed feature code.
 *
 * Nothing creates that link today, so until this test the property held by
 * omission and nothing said so. It is asserted for BOTH artifacts, because the
 * safe invariant is "never a link out of the worktree", not "always present":
 * a repo with no lockfile gets no node_modules and no build, and that is
 * isolation too.
 *
 * lstat, never stat or existsSync: stat follows a link, so a dist symlinked into
 * the primary tree answers as a perfectly good directory. A check that cannot
 * see the link is not worth running.
 *
 * The fixture's `prepare` mirrors this repo's own (`tsc && chmod +x
 * dist/index.js`), which makes this the live case rather than a hypothetical:
 * provision's frozen install really does build a dist inside the worktree, so a
 * link there would be written through on the very first provision.
 */
test("a freshly provisioned worktree's node_modules and dist are its own, never links out", async () => {
  const { repo, opts, cleanup } = await makeRepo({ nodePackage: true, buildsOnPrepare: true });
  try {
    const rec = await provisionWorktree(opts, "artifacts");
    assert.equal(rec.dependencies?.status, "installed", "the repo's own frozen install ran");

    for (const name of ["node_modules", "dist"]) {
      const st = await fsp.lstat(path.join(rec.worktreePath, name)).catch(() => null);
      if (!st) continue; // absent is fine; linked is not
      assert.equal(st.isSymbolicLink(), false, `${name} is not a symlink out of the worktree`);
      assert.ok(st.isDirectory(), `${name} is the worktree's own directory`);
    }

    // The install ran `prepare`, so the worktree has a real dist — and it is ITS
    // OWN: the build wrote down the tree it ran in, and nothing of the primary's
    // dist is visible through it.
    const dist = path.join(rec.worktreePath, "dist");
    assert.ok(fs.existsSync(dist), "provision's install built a dist inside the worktree");
    const builtIn = (await fsp.readFile(path.join(dist, "built.txt"), "utf8")).trim();
    assert.ok(samePathish(builtIn, rec.worktreePath), `dist was built in ${builtIn}, not the worktree`);
    assert.equal(fs.existsSync(path.join(dist, "marker.txt")), false, "the primary's dist is not visible through it");

    // And the primary tree holds exactly what it held before, both ways round:
    // its own artifacts survived, and the worktree's build did not land in them.
    for (const name of ["node_modules", "dist"]) {
      assert.equal(
        await fsp.readFile(path.join(repo, name, "marker.txt"), "utf8"),
        name === "dist" ? "build\n" : "deps\n",
        `the primary's ${name} is untouched by provisioning a worktree`,
      );
    }
    assert.equal(
      fs.existsSync(path.join(repo, "dist", "built.txt")),
      false,
      "the worktree's build never wrote the primary's dist",
    );
  } finally {
    await cleanup();
  }
});

test("teardown removes the worktree's own build output and never follows a legacy link", async () => {
  const { repo, opts, cleanup } = await makeRepo();
  try {
    // Two features: one provisioned normally, one doctored to look like a
    // worktree the OLD build left behind, symlinks and all. Both must tear down,
    // and neither may take the primary's artifacts with it.
    const own = await provisionWorktree(opts, "own");
    await fsp.mkdir(path.join(own.worktreePath, "node_modules"), { recursive: true });
    await fsp.writeFile(path.join(own.worktreePath, "node_modules", "local.txt"), "mine\n", "utf8");

    const legacy = await provisionWorktree(opts, "legacy");
    for (const name of ["node_modules", "dist"]) {
      await fsp.symlink(path.join(repo, name), path.join(legacy.worktreePath, name), "dir");
    }

    for (const rec of [own, legacy]) {
      const result = await teardownWorktree(opts, rec.feature);
      assert.equal(result.worktreeRemoved, true, `${rec.feature} worktree removed`);
      assert.equal(fs.existsSync(rec.worktreePath), false, `${rec.feature} is gone from disk`);
    }

    for (const name of ["node_modules", "dist"]) {
      assert.equal(
        await fsp.readFile(path.join(repo, name, "marker.txt"), "utf8"),
        name === "dist" ? "build\n" : "deps\n",
        `the primary's ${name} is untouched by teardown`,
      );
    }
  } finally {
    await cleanup();
  }
});

